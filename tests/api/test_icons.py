"""v1.14.0 — inline SVG icon set; v1.19.0 — Lucide everywhere.

User report on the VM actions row: the emoji icons read as a jumble —
some rendered as full-colour images (📸 📝), others as thin glyphs (■ ⚙),
with sizes varying per platform and poor legibility at 16 px. 1.14.0
replaced that row with a hand-drawn monochrome set inheriting
`currentColor`; 1.19.0 generalises the approach to the whole console with
the Lucide set, vendored and regenerated by scripts/gen-icons.py.

These tests pin the contract:
  * icons.js stays theme-aware (currentColor, viewBox 24) and keeps the
    semantic names call sites rely on;
  * no rendered source (templates, JS modules, CSS content:) carries a
    pictograph any more — typographic arrows in prose are allowed;
  * every icon name referenced anywhere exists in the generated table, and
    the table matches the generator's manifest;
  * the Lucide licence ships with the tarball.
"""

import importlib.util
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
WEB = ROOT / "web"
JS = WEB / "static" / "js"
CSS = WEB / "static" / "css" / "style.css"
TEMPLATES = WEB / "templates"
ICONS = (JS / "icons.js").read_text()

# Emoji ranges we do NOT want as action-button icons any more.
EMOJI_RE = re.compile("[\U0001F300-\U0001FAFF☀-➿]")

# Everything pictographic that used to be sprinkled through the UI: emoji,
# dingbats, arrows used as controls, geometric shapes, technical symbols
# (⏳ ⏸ ⏻), enclosed ⓘ, braille drag handle ⠿, regional-indicator flags and
# the variation selector. Typographic arrows → ← ↔ stay allowed in prose.
PICTOGRAPH_RE = re.compile(
    "[\U0001F000-\U0001FAFF"      # emoji blocks
    "\U0001F1E6-\U0001F1FF"       # regional indicators (flags)
    "☀-➿"               # misc symbols + dingbats
    "⬀-⯿"               # misc symbols and arrows (⬆ ⬇ ⬢)
    "■-◿"               # geometric shapes (■ ▶ ▼ ● ○)
    "⌀-⏿"               # misc technical (⏳ ⏱ ⏸ ⏻ ⌜)
    "↑↓↕-⇿"          # arrows used as controls (→ ← ↔ stay typographic)
    "ⓘℹ⠿⊡⟳️]"
)

ICON_REF_RE = re.compile(
    r"Icons\.(?:svg|el|dataUri)\(\s*'([A-Za-z0-9]+)'"
    r"|data-icon=\"([A-Za-z0-9]+)\""
    r"|\bicon:\s*'([A-Za-z0-9]+)'"
)

SHIPPED_SOURCES = sorted(
    [p for p in TEMPLATES.glob("*.html")]
    + [p for p in JS.glob("*.js")]
    + [CSS]
)


def _strip_comments(text: str, suffix: str) -> str:
    """Drop block/line comments so documentation may still mention glyphs."""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    if suffix == ".html":
        text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    if suffix == ".js":
        # Whole-line // comments and JSDoc-style ' * ' lines only: an inline
        # '//' inside a URL or string must not swallow real code.
        text = "\n".join(
            "" if re.match(r"\s*(//|\*)", ln) else ln for ln in text.splitlines()
        )
    return text


def _paths_keys() -> set:
    block = ICONS.split("BEGIN GENERATED", 1)[1].split("END GENERATED", 1)[0]
    return set(re.findall(r"^\s{4}([A-Za-z_][A-Za-z0-9_]*):", block, flags=re.M))


def _load_generator():
    spec = importlib.util.spec_from_file_location(
        "gen_icons", ROOT / "scripts" / "gen-icons.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


