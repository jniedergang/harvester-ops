# ---------------------------------------------------------------- 1.19.0

def test_no_pictographs_in_shipped_sources():
    """Every rendered glyph is an SVG now. Comments may still describe the
    old emoji; code and markup may not carry one."""
    offenders = []
    for path in SHIPPED_SOURCES:
        if "vendor" in path.parts:
            continue
        clean = _strip_comments(path.read_text(), path.suffix)
        for lineno, line in enumerate(clean.splitlines(), 1):
            hit = PICTOGRAPH_RE.search(line)
            if hit:
                offenders.append(f"{path.relative_to(ROOT)}:{lineno}: {hit.group(0)!r}")
    assert not offenders, "pictographs left in shipped sources:\n" + "\n".join(offenders)


def test_css_content_has_no_glyphs():
    """Pseudo-element icons go through the generated --icon-* masks."""
    values = re.findall(r"content:\s*'([^']*)'", CSS.read_text())
    bad = [v for v in values if PICTOGRAPH_RE.search(v)]
    assert not bad, f"glyphs in CSS content: {bad}"
    css = CSS.read_text()
    for var in ("--icon-check", "--icon-x", "--icon-sort", "--icon-sort-asc", "--icon-sort-desc"):
        assert f"{var}:" in css, f"missing generated mask {var}"
        assert f"var({var})" in css, f"generated mask {var} is unused"


def test_every_referenced_icon_exists():
    keys = _paths_keys()
    assert len(keys) >= 80
    missing = set()
    for path in SHIPPED_SOURCES:
        if "vendor" in path.parts or path == CSS:
            continue
        for m in ICON_REF_RE.finditer(path.read_text()):
            name = next(g for g in m.groups() if g)
            if name not in keys:
                missing.add(f"{path.name}: {name}")
    assert not missing, f"icon names referenced but not generated: {sorted(missing)}"


def test_manifest_matches_generated_block():
    gen = _load_generator()
    assert set(gen.ICONS) == _paths_keys(), (
        "run scripts/gen-icons.py after editing the manifest")
    assert f"lucide-static {gen.LUCIDE_VERSION}" in ICONS
    assert f"lucide-static {gen.LUCIDE_VERSION}" in CSS.read_text()
    assert gen.LUCIDE_INTEGRITY.startswith("sha512-")
    for name in gen.CSS_MASKS.values():
        assert name in gen.ICONS


def test_generated_bodies_inherit_stroke_colour():
    """Lucide children must carry no stroke/fill of their own, otherwise
    currentColor would not reach them and the theme switcher breaks."""
    block = ICONS.split("BEGIN GENERATED", 1)[1].split("END GENERATED", 1)[0]
    assert "stroke=" not in block
    # a few Lucide glyphs carry a solid dot; it must still follow the text colour
    assert not set(re.findall(r'fill="([^"]*)"', block)) - {"currentColor", "none"}


def test_lucide_licence_is_vendored():
    vendor = WEB / "static" / "vendor" / "lucide"
    licence = (vendor / "LICENSE").read_text()
    assert "ISC License" in licence
